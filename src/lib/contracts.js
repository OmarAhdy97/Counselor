import { tafqit, formatAmount } from './tafqit'
import { fmt } from './dates'

/**
 * Contract drafts. They are starting points for a lawyer to review, not finished legal advice:
 * the UI says so and the text stays fully editable before printing.
 */

const party = (name, nid, addr) =>
  `${name || '……'}${nid ? `، رقم قومي ${nid}` : ''}${addr ? `، ومقيم/ة ${addr}` : ''}`

const money = (v) => {
  if (v === '' || v === undefined || v === null) return '…… جنيه'
  try {
    return `${formatAmount(v)} جنيه (${tafqit(v)})`
  } catch {
    return '…… جنيه'
  }
}

const date = (v) => (v ? fmt(v) : '……/……/……')
const common = (v) => `حُرر هذا العقد في ${v.place || '……'} بتاريخ ${date(v.signDate)} من نسختين بيد كل طرف نسخة للعمل بموجبها.`

