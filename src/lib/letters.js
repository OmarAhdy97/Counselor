export function letterValues(c, { displayName, branch, amount } = {}) {
  const v = {
    التاريخ: fmt(today()),
    المستشار: displayName || '',
    الفرع: branch || '',
    المبلغ: amount ? Number(amount).toLocaleString('en-US') : '……',
    المبلغ_بالحروف: amount ? safeTafqit(amount) : '……',
  }
  if (!c) return v
  return {
    ...v,
    رقم_الدعوى: caseTitle(c),
    المحكمة: c.court || '',
    المدعي: c.plaintiff || '……',
    المدعى_عليه: c.defendant || '……',
    نوع_الدعوى: c.case_type || '……',
    الجلسة_القادمة: c.next_session ? fmt(c.next_session) : '……',
    تاريخ_الحكم: c.ruling_date ? fmt(c.ruling_date) : '……',
    منطوق_الحكم: c.ruling_text || '……',
    ميعاد_الطعن: c.appeal_deadline ? fmt(c.appeal_deadline) : '……',
  }
}

function safeTafqit(a) {
  try {
    return tafqit(a)
  } catch {
    return '……'
  }
}

export function fillTemplate(text, values) {
  return text.replace(/\{\{([^}]+)\}\}/g, (_, k) => values[k.trim()] ?? '……')
}
